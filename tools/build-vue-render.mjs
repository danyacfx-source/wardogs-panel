#!/usr/bin/env node
/**
 * Precompile the Vue templates embedded in index.html and panel.html.
 *
 * The generated render functions are regular JavaScript, so browsers do not
 * need eval()/Function() and the application can use a strict CSP.
 */

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const vuePath = path.join(root, "static", "vendor", "vue.global.prod.js");
const startMarker = "<!-- WARDOGS_APP_TEMPLATE_START -->";
const endMarker = "<!-- WARDOGS_APP_TEMPLATE_END -->";
const checkOnly = process.argv.includes("--check");

const generatedSources = [];
function decodeHtml(value) {
  return String(value)
    .replaceAll("&quot;", "\"")
    .replaceAll("&apos;", "'")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&amp;", "&");
}

// Vue's browser compiler uses a detached <div> only to decode HTML entities.
// A tiny DOM shim keeps this build step dependency-free in Node.
const decoderElement = {
  _html: "",
  set innerHTML(value) {
    this._html = String(value);
  },
  get textContent() {
    return decodeHtml(this._html);
  },
  children: [{
    getAttribute() {
      const match = decoderElement._html.match(/^<div foo="([\s\S]*)">$/);
      return decodeHtml(match ? match[1] : "");
    },
  }],
};
const sandbox = {
  console,
  document: {
    createElement() {
      return decoderElement;
    },
  },
  Function: function CapturedFunction(...args) {
    generatedSources.push(args);
    return Function(...args);
  },
};
sandbox.Function.prototype = Function.prototype;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(vuePath, "utf8"), sandbox, { filename: vuePath });

if (!sandbox.Vue || typeof sandbox.Vue.compile !== "function") {
  throw new Error("The vendored Vue compiler is unavailable");
}

function extractTemplate(htmlPath) {
  const html = fs.readFileSync(htmlPath, "utf8");
  const start = html.indexOf(startMarker);
  const end = html.indexOf(endMarker);
  if (start < 0 || end < 0 || end <= start) {
    throw new Error(`Template markers are missing or malformed in ${htmlPath}`);
  }
  return html.slice(start + startMarker.length, end).trim();
}

function compileTemplate(template, sourceName) {
  generatedSources.length = 0;
  globalThis.Vue = sandbox.Vue;
  try {
    sandbox.Vue.compile(template);
  } finally {
    delete globalThis.Vue;
  }
  const invocation = generatedSources.at(-1);
  const compiledBody = invocation?.at(-1);
  if (typeof compiledBody !== "string" || !compiledBody.includes("return function render")) {
    throw new Error(`Vue did not produce a render function for ${sourceName}`);
  }
  return [
    "/* This file is generated by tools/build-vue-render.mjs. Do not edit. */",
    "window.WARDOGS_RENDER = (function (Vue) {",
    compiledBody,
    "})(Vue);",
    "",
  ].join("\n");
}

let changed = false;
for (const name of ["index", "panel"]) {
  const htmlPath = path.join(root, "static", `${name}.html`);
  const outputPath = path.join(root, "static", `${name}.render.js`);
  const output = compileTemplate(extractTemplate(htmlPath), path.basename(htmlPath));
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (existing !== output) {
    changed = true;
    if (!checkOnly) {
      fs.writeFileSync(outputPath, output, "utf8");
      console.log(`generated ${path.relative(root, outputPath)}`);
    } else {
      console.error(`${path.relative(root, outputPath)} is stale`);
    }
  }
}

if (checkOnly && changed) {
  process.exitCode = 1;
} else if (checkOnly) {
  console.log("precompiled Vue render functions are current");
}